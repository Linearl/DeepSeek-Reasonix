export type EmojiEntry = {
  readonly char: string;
  /** 空格分隔的搜索关键词（英文 + 中文），已含常用别称。 */
  readonly keywords: string;
};

export type EmojiCategory = {
  readonly id: EmojiCategoryId;
  readonly emojis: readonly EmojiEntry[];
};

type RawEntry = readonly [char: string, keywords: string];

function category(id: EmojiCategoryId, raw: readonly RawEntry[]): EmojiCategory {
  return { id, emojis: raw.map(([char, keywords]) => ({ char, keywords })) };
}

