// Package unfiled reconciles checkpoint-recorded prompts against the session
// transcript (task 1023 phase 0). A turn's prompt is persisted to the
// checkpoint sidecar as a side effect of opening the turn; the same prompt is
// expected to appear as a user-role message in the transcript. When the
// checkpoint copy has no matching transcript message, the user's input never
// made it into the conversation — an "unfiled input" that only the checkpoint
// can still recover.
//
// The package is strictly read-only: it never writes the transcript, the
// event log, or the checkpoint store. ReadCheckpointInputs parses the
// turn-*.json files directly instead of going through checkpoint.New, whose
// constructor runs GC (payload expiry) as a side effect.
package unfiled

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"
)

// SystemRecoveryPrompt is the unattended auto-resume injection (task 544).
// Single source for reconciliation whitelisting; desktop/autopilot_resume.go
// carries the same string for its own injection path, and a desktop-side test
// pins the two in sync.
const SystemRecoveryPrompt = "Your previous turn stopped abnormally before the work could finish. Continue the interrupted work from where it stopped and carry it to completion; do not restate the plan and do not wait for input."

// systemPromptPrefixes are host/system-generated turn prompts that must never
// be reported as unfiled user input: their text is regenerable machinery, not
// user inspiration (task 1023 去重铁律：宿主注入/系统提示/跨会话消息折叠不计缺口).
var systemPromptPrefixes = []string{
	"[跨会话消息]",          // cross-session delivery (drain_inbox_tool)
	"[合并消息 ×",          // merged inbox consumption (control/inbox_merge)
	"[跨会话回信提醒",         // require_reply nudge (agent.CollabReplyNudgeMarker)
	"<context-state>",  // compaction state wrapper
	"<session-context", // host-generated snapshot wrapper
}

// systemPrompts are exact-match host injections (autopilot resume family,
// desktop-owned constants mirrored here; kept in sync by desktop tests).
var systemPrompts = map[string]bool{
	SystemRecoveryPrompt: true,
	// desktop/tabs.go autopilotResumePrompt (task-49 process restart).
	"The process restarted while this autopilot goal was running. Continue it from where it stopped; do not restate the plan or wait for input.": true,
	// desktop/autonomous_update_resume.go autonomousUpdateResumePrompt.
	"The app updated and restarted itself while this autopilot session was working. Continue from where it stopped; do not restate the plan or wait for input.": true,
}

// IsSystemPrompt reports whether a checkpoint prompt was generated by the host
// or the system rather than typed by the user.
func IsSystemPrompt(prompt string) bool {
	p := strings.TrimSpace(prompt)
	if p == "" {
		return false
	}
	if systemPrompts[p] {
		return true
	}
	for _, prefix := range systemPromptPrefixes {
		if strings.HasPrefix(p, prefix) {
			return true
		}
	}
	return false
}

// Input is one checkpoint-recorded prompt to reconcile.
type Input struct {
	Turn     int
	Time     time.Time
	Prompt   string
	MsgIndex int
}

// Entry is one unfiled input: the checkpoint recorded it, but no transcript
// user message carries its text. AnchorIndex is the transcript position the
// input belongs at (the checkpoint's MsgIndex — recorded before the user
// message is appended, so a filed input sits exactly at that index).
type Entry struct {
	Input
	AnchorIndex int
}

// Reconcile returns the inputs that have no matching transcript user message,
// oldest first. A input counts as filed when any transcript user message
// contains its text: filed messages carry host wrappers (<context-state>,
// capability routes, tool lists) around the user's words, so exact equality
// would false-positive every wrapped message. Matching folds whitespace so
// reflowed wrappers still reconcile.
//
// tl1372: classification-aware callers should use ReconcileGaps instead; this
// form keeps the task-1023 phase-0 semantics (every unmatched input is a gap,
// no fold/recovery evidence consulted).
func Reconcile(inputs []Input, filedTexts []string) []Entry {
	gaps := ReconcileGaps(inputs, filedTexts, ClassifyOptions{})
	out := make([]Entry, 0, len(gaps))
	for _, g := range gaps {
		if g.Class != GapUnfiled {
			// Unreachable with empty options; kept so Reconcile can never leak
			// a classified bucket into the phase-0 contract by accident.
			continue
		}
		out = append(out, g.Entry)
	}
	return out
}

// GapClass classifies why a checkpoint prompt is missing from the transcript
// (tl1372 误报修复). The banner semantics differ per class: a gap is only a
// "never reached the conversation" alarm when no side account explains its
// absence.
type GapClass string

const (
	// GapUnfiled — no transcript user message carries the text and no side
	// account explains the absence: the never-filed alarm the banner exists for.
	GapUnfiled GapClass = "unfiled"
	// GapFoldedArchive — a projection fold (self-heal diet) ran after the turn
	// was filed: the fold placeholder replaced the original text, so the
	// transcript no longer carries it. The input DID enter the conversation;
	// reporting it as never-filed is the 36-entry false-alarm class. Exempt
	// from the banner.
	GapFoldedArchive GapClass = "folded_archive"
	// GapPendingRecovery — the text lives in a recovery fork of the same
	// session topic: the runtime consumed it but its transcript saves were
	// CAS-refused (stale runtime), and the restart recovered it into a fork
	// instead of the parent transcript. Reportable, but as "pending recovery",
	// not "never entered". Gated behind the tl1372 experiment flag; with the
	// flag off this class collapses into GapUnfiled (现状单桶).
	GapPendingRecovery GapClass = "pending_recovery"
)

// Gap is one classified unfiled input.
type Gap struct {
	Entry
	Class GapClass
}

// ClassifyOptions carries the side-account evidence ReconcileGaps consults
// before calling an unmatched input a gap. Zero value = phase-0 semantics
// (no side accounts, everything unmatched is GapUnfiled).
type ClassifyOptions struct {
	// LatestFold is the time of the most recent completed projection fold
	// (repairlog fold action, agent.LatestFoldRepairTime). A checkpoint older
	// than that fold was in the transcript when the fold ran, so the fold
	// placeholder explains its absence. Zero = no fold history.
	LatestFold time.Time
	// RecoveredTexts are user-message texts read from the session topic's
	// recovery forks (read-only). Consulted only when AllowPendingRecovery.
	RecoveredTexts []string
	// AllowPendingRecovery is the tl1372 A2 experiment gate: false keeps the
	// single-bucket status quo (fork-recoverable gaps stay GapUnfiled).
	AllowPendingRecovery bool
}

// ReconcileGaps is Reconcile with the tl1372 side accounts: after the
// transcript containment check fails, a turn is classified
// GapFoldedArchive when its checkpoint predates the latest fold, and
// GapPendingRecovery when its text is present in a recovery fork and the
// experiment flag allows the split. Everything else stays GapUnfiled.
//
// Classification never files an input: folded/pending-recovery gaps are still
// not in the transcript — they just must not be advertised as "never reached
// the conversation".
func ReconcileGaps(inputs []Input, filedTexts []string, opts ClassifyOptions) []Gap {
	filed := make([]string, 0, len(filedTexts))
	for _, text := range filedTexts {
		if n := normalize(text); n != "" {
			filed = append(filed, n)
		}
	}
	recovered := make([]string, 0, len(opts.RecoveredTexts))
	if opts.AllowPendingRecovery {
		for _, text := range opts.RecoveredTexts {
			if n := normalize(text); n != "" {
				recovered = append(recovered, n)
			}
		}
	}
	var out []Gap
	for _, in := range inputs {
		prompt := strings.TrimSpace(in.Prompt)
		if prompt == "" || IsSystemPrompt(prompt) {
			continue
		}
		if containsAny(filed, normalize(prompt)) {
			continue
		}
		class := GapUnfiled
		switch {
		case !opts.LatestFold.IsZero() && !in.Time.IsZero() && in.Time.Before(opts.LatestFold):
			// 折叠免报（判则①主修）：fold 只折叠早于它的消息；checkpoint 早于
			// 最近一次完成折叠的 turn，其原文在折叠时必然在档，占位符解释了
			// 缺席。无时间戳的旧 checkpoint 证据不足，保守继续上报。
			class = GapFoldedArchive
		case opts.AllowPendingRecovery && containsAny(recovered, normalize(prompt)):
			// CAS 拒档形态（判则①补充）：原文在 recovery 副本里，是「待恢复」
			// 而非「未进入对话」。
			class = GapPendingRecovery
		}
		out = append(out, Gap{Entry: Entry{Input: in, AnchorIndex: in.MsgIndex}, Class: class})
	}
	sort.Slice(out, func(i, j int) bool {
		if out[i].AnchorIndex != out[j].AnchorIndex {
			return out[i].AnchorIndex < out[j].AnchorIndex
		}
		return out[i].Turn < out[j].Turn
	})
	return out
}

// containsAny reports whether any filed text contains the normalized prompt.
func containsAny(filed []string, prompt string) bool {
	if prompt == "" {
		return true
	}
	for _, text := range filed {
		if strings.Contains(text, prompt) {
			return true
		}
	}
	return false
}

// normalize folds whitespace so matching survives wrapper reflow.
func normalize(s string) string {
	return strings.Join(strings.Fields(s), " ")
}

// checkpointFile is the subset of turn-*.json this package reads. Prompt and
// MsgIndex are the reconciliation fields; the rest is tolerated-and-ignored so
// schema evolution (v1/v2/v3) never breaks the scan.
type checkpointFile struct {
	Turn     int       `json:"turn"`
	Time     time.Time `json:"time"`
	Prompt   string    `json:"prompt"`
	MsgIndex int       `json:"msgIndex"`
}

// ReadCheckpointInputs scans a session's .ckpt directory for turn-*.json
// prompt records, oldest turn first. Purely read-only. A missing directory,
// unreadable entries, or corrupt JSON are skipped silently — reconciliation
// degrades to "no evidence" instead of failing a diagnostic surface.
func ReadCheckpointInputs(ckptDir string) ([]Input, error) {
	if ckptDir == "" {
		return nil, nil
	}
	entries, err := os.ReadDir(ckptDir)
	if err != nil {
		if os.IsNotExist(err) {
			return nil, nil
		}
		return nil, err
	}
	var out []Input
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasPrefix(entry.Name(), "turn-") || !strings.HasSuffix(entry.Name(), ".json") {
			continue
		}
		raw, err := os.ReadFile(filepath.Join(ckptDir, entry.Name()))
		if err != nil {
			continue
		}
		var cf checkpointFile
		if err := json.Unmarshal(raw, &cf); err != nil {
			continue
		}
		if cf.Turn == 0 && cf.Prompt == "" {
			continue
		}
		out = append(out, Input{Turn: cf.Turn, Time: cf.Time, Prompt: cf.Prompt, MsgIndex: cf.MsgIndex})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Turn < out[j].Turn })
	return out, nil
}

// FormatEntry renders one entry for plain-text diagnostics.
func FormatEntry(e Entry) string {
	return fmt.Sprintf("turn %d (msgIndex %d, %s): %s", e.Turn, e.MsgIndex, e.Time.Format("2006-01-02 15:04:05"), firstLine(e.Prompt))
}

func firstLine(s string) string {
	if i := strings.IndexAny(s, "\r\n"); i >= 0 {
		return s[:i]
	}
	return s
}
