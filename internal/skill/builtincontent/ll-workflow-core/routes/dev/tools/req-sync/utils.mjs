/**
 * 解析当前任务上下文的所有路径。
 * 优先使用 profile-resolver 解析 .ll-workflow.yaml + directory-layout.yaml + route-registry.yaml，
 * 失败时降级到旧的 findTaskBase() 自动向上查找逻辑。
 *
 * @param {Object} [options]
 * @param {string} [options.workspaceRoot]  项目根
 * @param {string} [options.targetDevDir]   dev_xx 目录
 * @param {string} [options.version]        版本号
 * @param {string} [options.profileOverride] 显式 profile 名
 * @returns {{
 *   workspaceRoot: string,
 *   targetDevDir: string,
 *   version: string,
 *   baseDir: string,            // docs/1.task 根
 *   todoPath: string,           // B.todo
 *   donePath: string,           // B.2.done（不含 version）
 *   pausedPath: string,
 *   cancelledPath: string,
 *   inactivePath: string,
 *   requirementsIndexPath: string,
 *   taskReadmeIndexPath: string,
 *   docsIndexPath: string,
 *   docsReadmePath: string,
 *   changelogRoot: string,
 *   profileName: string,
 *   source: "profile-resolver" | "fallback-findTaskBase",
 * }}
 */
export function resolvePaths(options = {}) {
  try {
    const ctx = resolveProfile({
      workspaceRoot: options.workspaceRoot,
      targetDevDir: options.targetDevDir,
      version: options.version,
      profileOverride: options.profileOverride,
    });

    // task_base = docs_root/1.task
    const taskBase = join(ctx.resolveSlot("docs_root"), "1.task");
    return {
      workspaceRoot: ctx.workspaceRoot,
      targetDevDir: ctx.targetDevDir,
      version: ctx.version,
      baseDir: taskBase,
      todoPath: ctx.resolveSlot("task_todo_root"),
      donePath: ctx.resolveSlot("task_done_root"),
      pausedPath: ctx.resolveSlot("task_paused_root"),
      cancelledPath: ctx.resolveSlot("task_cancelled_root"),
      inactivePath: ctx.resolveSlot("task_inactive_root"),
      requirementsIndexPath: ctx.resolveSlot("task_requirements_index"),
      taskReadmeIndexPath: ctx.resolveSlot("task_readme_index"),
      docsIndexPath: ctx.resolveSlot("docs_index"),
      docsReadmePath: ctx.resolveSlot("docs_readme"),
      changelogRoot: ctx.resolveSlot("changelog_root"),
      profileName: ctx._raw?.extends ? ctx._raw.extends : "default",
      source: "profile-resolver",
    };
  } catch (e) {
    // profile-resolver 失败时降级
    const baseDir = findTaskBase();
    if (!baseDir) throw e;
    return {
      workspaceRoot: options.workspaceRoot || process.cwd(),
      targetDevDir: options.targetDevDir || "",
      version: options.version || "",
      baseDir,
      todoPath: join(baseDir, "B.todo"),
      donePath: join(baseDir, "B.2.done"),
      pausedPath: join(baseDir, "B.1.paused"),
      cancelledPath: join(baseDir, "B.3.cancelled"),
      inactivePath: join(baseDir, "A.inactive"),
      requirementsIndexPath: join(baseDir, "requirements.md"),
      taskReadmeIndexPath: join(baseDir, "README.md"),
      docsIndexPath: "",
      docsReadmePath: "",
      changelogRoot: "",
      profileName: "fallback",
      source: "fallback-findTaskBase",
    };
  }
}

/**
 * 向上查找 1.task 目录（向后兼容的旧 API，新代码请用 resolvePaths()）
 */
export function findTaskBase() {
  let dir = process.cwd();
  for (let i = 0; i < 10; i++) {
    const candidate = join(dir, "docs", "1.task");
    if (existsSync(candidate)) return candidate;
    const parent = resolve(dir, "..");
    if (parent === dir) break;
    dir = parent;
  }
  // 自动识别最新 dev_xx 版本（避免硬编码版本号）
  const devBase = resolve("02-dev");
  if (existsSync(devBase)) {
    const devDirs = readdirSync(devBase)
      .filter((d) => {
        if (!/^dev_\d+$/.test(d)) return false;
        try { return statSync(join(devBase, d)).isDirectory(); }
        catch { return false; }
      })
      .sort()
      .reverse();
    if (devDirs.length > 0) {
      const defaultPath = join(devBase, devDirs[0], "docs", "1.task");
      if (existsSync(defaultPath)) return defaultPath;
    }
  }
  return null;
}

/**
 * 查找 requirements.md（向后兼容）
 */
export function findRequirementsMd() {
  const base = findTaskBase();
  if (!base) return null;
  const reqPath = join(base, "requirements.md");
  return existsSync(reqPath) ? reqPath : null;
}

