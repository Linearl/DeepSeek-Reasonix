/**
 * 从任务包目录名中提取结构化信息
 * 目录名格式：v{VER}-r{REQID}-p{PRI}-{SLUG}
 */
export function parseDirName(dirName) {
  // 标准格式：v{VER}-r{REQID}-p{PRI}-{SLUG}
  const m = dirName.match(/^v(\d+)-r(\d+)-p(\d+)-(.+)$/);
  if (m) {
    return {
      version: `dev_${m[1]}`,
      reqId: parseInt(m[2], 10),
      priority: `p${m[3]}`,
      slug: m[4],
    };
  }
  // 非标准格式（无优先级）：v{VER}-r{REQID}-{SLUG}
  const m2 = dirName.match(/^v(\d+)-r(\d+)-(.+)$/);
  if (m2) {
    return {
      version: `dev_${m2[1]}`,
      reqId: parseInt(m2[2], 10),
      priority: "p1", // 默认
      slug: m2[3],
    };
  }
  return null;
}

/**
 * 从目录路径推断所在状态层
 */
export function inferStatusLayer(relPath) {
  for (const [layer, status] of Object.entries(DIR_STATUS_MAP)) {
    if (relPath.includes(`/${layer}/`) || relPath.startsWith(`${layer}/`)) {
      return { layer, status };
    }
  }
  return { layer: "unknown", status: "📋 待办" };
}

/**
 * 安全读取 JSON 文件
 */
export function readJsonSafe(filePath) {
  try {
    const raw = readFileSync(filePath, "utf-8");
    return JSON.parse(raw);
  } catch {
    return null;
  }
}

/**
 * 安全读取文本文件
 */
export function readTextSafe(filePath) {
  try {
    return readFileSync(filePath, "utf-8");
  } catch {
    return "";
  }
}

/**
 * 从 README.md 中提取专题信息
 */
export function parseReadme(readmePath) {
  const content = readTextSafe(readmePath);
  if (!content) return {};

  const info = {};

  // 提取需求编号
  const reqMatch = content.match(/需求编号[：:]\s*`?(REQ-\d+|`\d+`)/);
  if (reqMatch) {
    info.reqId = reqMatch[1].replace(/`/g, "");
  }

  // 提取专题名称
  const titleMatch = content.match(/专题名称[：:]\s*`([^`]+)`/);
  if (titleMatch) {
    info.title = titleMatch[1];
  }

  // 提取优先级
  const priMatch = content.match(/优先级[：:]\s*`?(P\d|p\d)/i);
  if (priMatch) {
    info.priority = priMatch[1].toLowerCase();
  }

  // 提取当前阶段
  const stageMatch = content.match(/当前阶段[：:]\s*`([^`]+)`/);
  if (stageMatch) {
    info.stage = stageMatch[1];
  }

  return info;
}

/**
 * 从目录结构中提取标题（从 REQ-*.md 的 heading 或目录 slug 推断）
 */
export function inferTitle(pkgPath, dirName, readmeInfo) {
  // 优先从 README 获取
  if (readmeInfo.title) return readmeInfo.title;

  // 从 slug 推断（kebab-case → 空格分隔）
  const parsed = parseDirName(dirName);
  if (parsed) {
    return parsed.slug
      .split("-")
      .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
      .join(" ");
  }

  return dirName;
}

/**
 * 调用 git log 获取目录的首次和末次提交日期
 * 注意：仅在 --git 参数启用时调用，因为每个包需要 2 次 git 命令，200+ 包会很慢
 */
export function gitLogDates(pkgPath, repoRoot) {
  try {
    const relPath = pkgPath.replace(repoRoot + "/", "").replace(/\\/g, "/");
    const firstCmd = `git log --diff-filter=A --follow --format=%ad --date=short -- "${relPath}" | tail -1`;
    const lastCmd = `git log -1 --format=%ad --date=short -- "${relPath}"`;
    const first = execSync(firstCmd, { cwd: repoRoot, encoding: "utf-8", timeout: 5000 }).trim();
    const last = execSync(lastCmd, { cwd: repoRoot, encoding: "utf-8", timeout: 5000 }).trim();
    return { start: first || null, end: last || null };
  } catch {
    return { start: null, end: null };
  }
}

