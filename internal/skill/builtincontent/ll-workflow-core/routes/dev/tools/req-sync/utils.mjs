/**
 * 在中文与英文/数字之间插入半角空格（单遍扫描，避免链式替换冲突）
 */
export function normalizeChineseSpacing(text) {
  if (!text) return text;
  const chars = [...text];
  const insertPositions = [];
  for (let i = 0; i < chars.length - 1; i++) {
    const a = chars[i].charCodeAt(0);
    const b = chars[i + 1].charCodeAt(0);
    const aIsCN = a >= 0x4e00 && a <= 0x9fff;
    const bIsCN = b >= 0x4e00 && b <= 0x9fff;
    const aIsEN = (a >= 0x41 && a <= 0x5a) || (a >= 0x61 && a <= 0x7a) || (a >= 0x30 && a <= 0x39);
    const bIsEN = (b >= 0x41 && b <= 0x5a) || (b >= 0x61 && b <= 0x7a) || (b >= 0x30 && b <= 0x39);
    if ((aIsCN && bIsEN) || (aIsEN && bIsCN)) {
      // 已有空格则跳过
      if (chars[i] !== " " && chars[i + 1] !== " ") {
        insertPositions.push(i + 1);
      }
    }
  }
  let result = text;
  for (let i = insertPositions.length - 1; i >= 0; i--) {
    result = result.slice(0, insertPositions[i]) + " " + result.slice(insertPositions[i]);
  }
  return result;
}
