export function parseArgs(argv) {
  const args = { _: [], command: null, category: null, count: "5", apply: false, git: false, cleanupStale: false };
  const raw = argv.slice(2);

  for (let i = 0; i < raw.length; i++) {
    const arg = raw[i];
    if (arg === "--help" || arg === "-h") {
      args.help = true;
    } else if (arg === "--category" || arg === "-c") {
      args.category = raw[++i] || null;
    } else if (arg === "--count" || arg === "-n") {
      args.count = raw[++i] || "5";
    } else if (arg === "--apply") {
      args.apply = true;
    } else if (arg === "--git") {
      args.git = true;
    } else if (arg === "--cleanup-stale") {
      args.cleanupStale = true;
    } else if (arg === "--workspace-root") {
      args.workspaceRoot = raw[++i] || null;
    } else if (arg === "--profile") {
      args.profileOverride = raw[++i] || null;
    } else if (!arg.startsWith("-")) {
      args._.push(arg);
    }
  }

  // 第一个位置参数是命令名
  if (args._.length > 0) {
    args.command = args._[0];
    args._ = args._.slice(1);
  }

  return args;
}

