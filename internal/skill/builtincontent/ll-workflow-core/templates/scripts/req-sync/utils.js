function parseDirName(dirName) {
  const m = dirName.match(/^v(\d+\.?\d*)-r(\d+)-(\w+)-(.+)$/);
  if (m) {
    return {
      version: m[1],
      reqId: parseInt(m[2], 10),
      complexity: m[3],
      slug: m[4],
    };
  }
  const m2 = dirName.match(/^v(\d+)-r(\d+)-p(\d+)-(.+)$/);
  if (m2) {
    return {
      version: `dev_${m2[1]}`,
      reqId: parseInt(m2[2], 10),
      complexity: `p${m2[3]}`,
      slug: m2[4],
    };
  }
  const m3 = dirName.match(/^v(\d+)-r(\d+)-(.+)$/);
  if (m3) {
    return {
      version: `dev_${m3[1]}`,
      reqId: parseInt(m3[2], 10),
      complexity: "",
      slug: m3[3],
    };
  }
  return null;
}

function inferStatusLayer(relPath) {
  for (const [layer, status] of Object.entries(DIR_STATUS_MAP)) {
    if (relPath.includes(`/${layer}/`) || relPath.startsWith(`${layer}/`)) {
      return { layer, status };
    }
  }
  return { layer: "unknown", status: LIFECYCLE_STATUS_MAP.todo };
}

function readJsonSafe(filePath) {
  try {
    const raw = readFileSync(filePath, "utf-8");
    return JSON.parse(raw);
  } catch {
    return null;
  }
}

function readTextSafe(filePath) {
  try {
    return readFileSync(filePath, "utf-8");
  } catch {
    return "";
  }
}

function parseReadme(readmePath) {
  const content = readTextSafe(readmePath);
  if (!content) return {};
  const info = {};
  const reqMatch = content.match(/需求编号[：:]\s*`?(REQ-(\d+)|(\d+))`?/);
  if (reqMatch) info.reqId = (reqMatch[2] || reqMatch[3]).replace(/`/g, "");
  const titleMatch = content.match(/专题名称[：:]\s*`([^`]+)`/);
  if (titleMatch) info.title = titleMatch[1];
  const priMatch = content.match(/优先级[：:]\s*`?(P\d|p\d)/i);
  if (priMatch) info.priority = priMatch[1].toLowerCase();
  const stageMatch = content.match(/当前阶段[：:]\s*`([^`]+)`/);
  if (stageMatch) info.stage = stageMatch[1];
  return info;
}

function inferTitle(pkgPath, dirName, readmeInfo) {
  if (readmeInfo.title) return readmeInfo.title;
  const parsed = parseDirName(dirName);
  if (parsed) {
    return parsed.slug.split("-").map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join(" ");
  }
  return dirName;
}

/**
 * 调用 git log 获取目录的首次和末次提交日期
 * 使用 execFileSync + 参数数组形式,避免 shell 模板字符串拼接导致的 command injection 风险。
 */
function gitLogDates(pkgPath, repoRoot) {
  try {
    const relPath = pkgPath.replace(repoRoot + "/", "").replace(/\\/g, "/");
    const commonOpts = { cwd: repoRoot, encoding: "utf-8", timeout: 5000 };
    const first = execFileSync(
      "git",
      ["log", "--diff-filter=A", "--follow", "--format=%ad", "--date=short", "--", relPath],
      commonOpts,
    ).trim();
    const last = execFileSync(
      "git",
      ["log", "-1", "--format=%ad", "--date=short", "--", relPath],
      commonOpts,
    ).trim();
    return { start: first || null, end: last || null };
  } catch {
    return { start: null, end: null };
  }
}

function parseRequirementsMd(filePath) {
  const content = readTextSafe(filePath);
  if (!content) return new Map();
  const lines = content.split("\n");
  const reqMap = new Map();
  let inTable = false;
  let headerCols = [];

  for (const line of lines) {
    const trimmed = line.trim();
    if (trimmed.startsWith("## 4.")) break;
    if (trimmed.match(/^\|[\s-]+\|/)) {
      inTable = true;
      continue;
    }
    if (trimmed.startsWith("|") && !inTable) {
      const cols = trimmed.split("|").map((c) => c.trim()).filter(Boolean);
      if (cols.includes("编号") && cols.includes("当前状态")) {
        headerCols = cols;
        continue;
      }
    }
    if (trimmed.startsWith("|") && inTable && headerCols.length > 0) {
      const cells = trimmed.split("|").map((c) => c.trim()).filter(Boolean);
      if (cells.length < 3) continue;
      const idx = {};
      headerCols.forEach((h, i) => { idx[h] = i; });
      const idStr = cells[idx["编号"]] || "";
      const idNum = parseInt(idStr, 10);
      if (isNaN(idNum)) continue;
      reqMap.set(idNum, {
        id: idNum,
        title: cells[idx["任务标题"]] || "",
        priority: cells[idx["优先级"]] || "",
        status: cells[idx["当前状态"]] || "",
        source: cells[idx["来源层"]] || "",
        targetVersion: cells[idx["目标版本"]] || "",
        startDate: cells[idx["开始日期"]] || "-",
        endDate: cells[idx["完成日期"]] || "-",
        docPath: cells[idx["详情文档"]] || "",
        note: cells[idx["备注"]] || "",
      });
    }
  }
  return reqMap;
}

function findTaskBase(docsOverride) {
  if (docsOverride) {
    const candidate = join(docsOverride, "1.task");
    if (existsSync(candidate)) return candidate;
  }
  const defaultCandidate = join("docs_dev", "1.task");
  if (existsSync(defaultCandidate)) return defaultCandidate;
  let dir = process.cwd();
  for (let i = 0; i < 10; i++) {
    const candidate = join(dir, "docs_dev", "1.task");
    if (existsSync(candidate)) return candidate;
    const candidate2 = join(dir, "docs", "1.task");
    if (existsSync(candidate2)) return candidate2;
    const parent = resolve(dir, "..");
    if (parent === dir) break;
    dir = parent;
  }
  return null;
}

function findRequirementsMd(docsOverride) {
  const base = findTaskBase(docsOverride);
  if (!base) return null;
  const reqPath = join(base, "requirements.md");
  return existsSync(reqPath) ? reqPath : null;
}

function parseArgs(argv) {
  const args = {
    _: [], command: null, category: null, count: "5",
    apply: false, git: false, cleanupStale: false,
    backup: false, docs: null,
  };
  const raw = argv.slice(2);
  for (let i = 0; i < raw.length; i++) {
    const arg = raw[i];
    if (arg === "--help" || arg === "-h") args.help = true;
    else if (arg === "--category" || arg === "-c") args.category = raw[++i] || null;
    else if (arg === "--count" || arg === "-n") args.count = raw[++i] || "5";
    else if (arg === "--apply") args.apply = true;
    else if (arg === "--git") args.git = true;
    else if (arg === "--cleanup-stale") args.cleanupStale = true;
    else if (arg === "--backup") args.backup = true;
    else if (arg === "--docs") args.docs = raw[++i] || null;
    else if (!arg.startsWith("-")) args._.push(arg);
  }
  if (args._.length > 0) {
    args.command = args._[0];
    args._ = args._.slice(1);
  }
  return args;
}

