# tl 1597 (part 2/3): health check + fast restore for main-repo node_modules.
#
# Companion of backup-node_modules-golden.ps1. Detects the "gutted
# node_modules" incident shape (.bin/tsc.cmd missing, .pnpm thinned, top
# level emptied) and restores from the golden copy in seconds-to-minutes
# (measured, see tl1597 acceptance log).
#
# CHECK items (fast, read-only, seconds):
#   1. node_modules exists as a directory
#   2. .bin/tsc.cmd present (the exact artifact whose disappearance
#      constituted the 2026-11-13 incidents)
#   3. .pnpm entry count >= -MinPnpmEntries (default 100; healthy=463 on
#      2026-11-15) -- a "quick integrity probe", not a full hash audit
#   4. top-level entry count >= -MinTopLevel (default 20; healthy=41)
#   5. .pnpm/typescript@* present
#   Exit code: 0 = healthy, 1 = unhealthy, 2 = usage/internal error.
#
# RESTORE strategy (deliberate): directory-level robocopy /MIR from golden,
#   NOT a pnpm re-install call:
#   - local copy has no network dependency and a predictable duration
#     (seconds~minutes measured);
#   - the golden copy is a pre-verified healthy snapshot (backup script
#     health-checks the source before copying);
#   - pnpm re-install needs network + store resolution, minutes-scale with
#     more failure modes. Use pnpm install only as the fallback when the
#     golden copy itself is missing/unhealthy (this script refuses then).
#
# USAGE:
#   # check (default, read-only):
#   powershell -ExecutionPolicy Bypass -File scripts\check-node_modules-health.ps1
#   # plan the restore without copying:
#   powershell ... -File scripts\check-node_modules-health.ps1 -Action Restore -DryRun
#   # restore (refuses if currently healthy unless -Force):
#   powershell ... -File scripts\check-node_modules-health.ps1 -Action Restore
# OUTPUT: per-item verdicts, restore/verify timings; after restore it
#   re-checks health AND runs .bin/tsc.cmd --version as the end-to-end proof.

param(
    # node_modules to check/restore. Default: main repo desktop/frontend/node_modules.
    [string]$NodeModulesDir,

    # Golden copy source. Default: <parent-of-main-repo>\golden\node_modules-desktop-frontend
    [string]$GoldenDir,

    [ValidateSet("Check", "Restore")]
    [string]$Action = "Check",

    [int]$MinPnpmEntries = 100,
    [int]$MinTopLevel = 20,

    # Restore even when the current state passes the health check.
    [switch]$Force,

    [switch]$DryRun
)

$ErrorActionPreference = "Stop"

function Get-MainRepoRoot {
    $lines = @(& git worktree list --porcelain)
    if ($LASTEXITCODE -ne 0) { throw "git worktree list failed (run inside the reasonix repo or a worktree)" }
    foreach ($line in $lines) {
        if ($line -like "worktree *") { return $line.Substring("worktree ".Length) }
    }
    throw "could not parse main repo root from git worktree list"
}

function Get-NodeModulesStats {
    param([Parameter(Mandatory = $true)][string]$Path)
    $stats = @{
        Exists        = (Test-Path -LiteralPath $Path -PathType Container)
        TscCmd        = $false
        PnpmEntries   = 0
        TopDirs       = 0
        HasTypescript = $false
    }
    if (-not $stats.Exists) { return $stats }
    $stats.TscCmd = (Test-Path -LiteralPath (Join-Path $Path ".bin\tsc.cmd") -PathType Leaf)
    $pnpmDir = Join-Path $Path ".pnpm"
    if (Test-Path -LiteralPath $pnpmDir -PathType Container) {
        $stats.PnpmEntries = @(Get-ChildItem -LiteralPath $pnpmDir -Force -Directory).Count
        $stats.HasTypescript = (@(Get-ChildItem -LiteralPath $pnpmDir -Force -Directory -Filter "typescript@*").Count -gt 0)
    }
    $stats.TopDirs = @(Get-ChildItem -LiteralPath $Path -Force).Count
    return $stats
}

# Returns $true when healthy; prints per-item verdicts either way.
function Test-NodeModulesHealth {
    param(
        [Parameter(Mandatory = $true)][string]$Path,
        [Parameter(Mandatory = $true)][hashtable]$Stats,
        [Parameter(Mandatory = $true)][int]$MinPnpm,
        [Parameter(Mandatory = $true)][int]$MinTop,
        [Parameter(Mandatory = $true)][string]$Label
    )
    $fail = @()
    if (-not $Stats.Exists) {
        $fail += "node_modules missing or not a directory"
    } else {
        if (-not $Stats.TscCmd) { $fail += ".bin/tsc.cmd MISSING (gutted-incident signature)" }
        if ($Stats.PnpmEntries -lt $MinPnpm) { $fail += (".pnpm entries {0} < threshold {1}" -f $Stats.PnpmEntries, $MinPnpm) }
        if ($Stats.TopDirs -lt $MinTop) { $fail += ("top-level entries {0} < threshold {1}" -f $Stats.TopDirs, $MinTop) }
        if (-not $Stats.HasTypescript) { $fail += ".pnpm/typescript@* MISSING" }
    }
    if ($fail.Count -eq 0) {
        Write-Host ("[{0}] HEALTHY: tsc.cmd=present .pnpm={1} top={2} typescript=present" -f $Label, $Stats.PnpmEntries, $Stats.TopDirs)
        return $true
    }
    Write-Host ("[{0}] UNHEALTHY ({1} problem(s)):" -f $Label, $fail.Count)
    foreach ($f in $fail) { Write-Host ("  - " + $f) }
    return $false
}

# --- resolve paths -----------------------------------------------------------

$mainRepoRoot = Get-MainRepoRoot
if (-not $NodeModulesDir) { $NodeModulesDir = Join-Path $mainRepoRoot "desktop\frontend\node_modules" }
if (-not $GoldenDir) { $GoldenDir = Join-Path (Split-Path -Parent $mainRepoRoot) "golden\node_modules-desktop-frontend" }

Write-Host "== tl1597 node_modules health ($Action) =="
Write-Host ("target: $NodeModulesDir")
Write-Host ("golden: $GoldenDir")

# --- CHECK -------------------------------------------------------------------

$sw = [System.Diagnostics.Stopwatch]::StartNew()
$stats = Get-NodeModulesStats -Path $NodeModulesDir
$healthy = Test-NodeModulesHealth -Path $NodeModulesDir -Stats $stats -MinPnpm $MinPnpmEntries -MinTop $MinTopLevel -Label "current"
$sw.Stop()

$goldenStats = Get-NodeModulesStats -Path $GoldenDir
$goldenOk = Test-NodeModulesHealth -Path $GoldenDir -Stats $goldenStats -MinPnpm $MinPnpmEntries -MinTop $MinTopLevel -Label "golden"

if ($Action -eq "Check") {
    Write-Host ("check finished in {0}s -> {1}" -f $sw.Elapsed.TotalSeconds.ToString("0.0"), $(if ($healthy) { "HEALTHY" } else { "UNHEALTHY" }))
    if (-not $healthy) {
        if (-not $goldenOk) {
            Write-Host "golden copy is ALSO unhealthy: restore from golden impossible; re-run the backup script after a fresh 'pnpm install --frozen-lockfile' in the main repo."
        } else {
            Write-Host "recovery available: re-run with -Action Restore"
        }
        exit 1
    }
    exit 0
}

# --- RESTORE -----------------------------------------------------------------

if ($goldenOk -eq $false) {
    throw "golden copy is missing or unhealthy ($GoldenDir); refusing to restore from it. Fix: 'pnpm install --frozen-lockfile' in main-repo desktop/frontend, then run backup-node_modules-golden.ps1."
}
if ($healthy -and -not $Force) {
    throw "current node_modules already passes the health check; refusing to overwrite it (use -Force to override)."
}

if ($DryRun) {
    Write-Host "DRY-RUN plan:"
    Write-Host ("  1. robocopy /MIR `"$GoldenDir`" -> `"$NodeModulesDir`" (restore from golden)")
    Write-Host ("  2. re-run health check on target (must pass)")
    Write-Host "  3. run `"<target>\.bin\tsc.cmd --version`" as end-to-end proof"
    Write-Host "DRY-RUN: nothing restored. Re-run without -DryRun to execute."
    exit 0
}

Write-Host ("restoring from golden (robocopy /MIR)...")
$rsw = [System.Diagnostics.Stopwatch]::StartNew()
$null = & robocopy $GoldenDir $NodeModulesDir /MIR /NFL /NDL /NJH /NJS /NP /R:2 /W:2
$rc = $LASTEXITCODE
if ($rc -ge 8) { throw "robocopy restore failed with exit code $rc" }

# verify: health re-check must pass, then tsc must actually run.
$after = Get-NodeModulesStats -Path $NodeModulesDir
$afterOk = Test-NodeModulesHealth -Path $NodeModulesDir -Stats $after -MinPnpm $MinPnpmEntries -MinTop $MinTopLevel -Label "restored"
if (-not $afterOk) { throw "restore finished but target still fails the health check" }

$tscOut = & (Join-Path $NodeModulesDir ".bin\tsc.cmd") --version
if ($LASTEXITCODE -ne 0) { throw "post-restore 'tsc --version' failed with exit code $LASTEXITCODE" }
$rsw.Stop()

Write-Host ("restore DONE in {0}s (robocopy exit {1}); tsc --version -> {2}" -f $rsw.Elapsed.TotalSeconds.ToString("0.0"), $rc, ($tscOut -join " "))
