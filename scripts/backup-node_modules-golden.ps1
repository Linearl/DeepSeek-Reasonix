# tl 1597 (part 1/3): sync main-repo node_modules to a golden copy (backup).
#
# Background: in one day (2026-11-13) the main repo's
# desktop/frontend/node_modules was gutted 6 times by the
# "worktree junction transparent-delete" family (git worktree remove /
# Directory.Delete / recycle-bin traversing junctions inside worktrees).
# User decision: keep junctions in worktrees (10 wt saves ~3.4GB) and keep a
# golden copy of the main repo's node_modules as the recovery source. This
# script is part 1 of the 3-piece support kit: produce/update that golden copy.
#
# WHERE THE GOLDEN COPY LIVES (deliberate):
#   <parent-of-main-repo>\golden\node_modules-desktop-frontend
#   i.e. github-repo/golden/... -- OUTSIDE any git work tree, so
#   `git clean -fdx` and repo-scoped cleanup scripts can never touch it.
#   The main repo root is anchored via `git worktree list` (first entry is
#   always the main worktree), so the golden location is identical no matter
#   which worktree this script runs from. Override with -GoldenDir.
#
# SYNC POLICY (deliberate): explicit invocation only (also fine to call right
#   after `pnpm install --frozen-lockfile` in the MAIN repo's
#   desktop/frontend). No automatic hook baked into install:
#   - a failed/interrupted install would let a half-gutted state be mirrored
#     into the golden copy, poisoning the recovery source;
#   - golden only needs updating when dependency versions actually change,
#     so the manual cost is low while reliability stays absolute.
#
# PRECONDITIONS:
#   - the SOURCE (main repo desktop/frontend/node_modules) must be healthy,
#     checked BEFORE any copy: .bin/tsc.cmd present + .pnpm entry count at
#     least -MinPnpmEntries. A gutted source is refused (never back up a
#     broken state over the last good snapshot).
#
# USAGE:
#   powershell -ExecutionPolicy Bypass -File scripts\backup-node_modules-golden.ps1
#   powershell ... -File scripts\backup-node_modules-golden.ps1 -DryRun     # plan only
#   powershell ... -File scripts\backup-node_modules-golden.ps1 -MinPnpmEntries 200
# OUTPUT: health precheck result, robocopy stats, elapsed time, golden
#   manifest written to <golden>\manifest.json (timestamp + entry counts).

param(
    # Source node_modules to back up. Default: main repo desktop/frontend/node_modules.
    [string]$SourceDir,

    # Golden copy destination. Default: <parent-of-main-repo>\golden\node_modules-desktop-frontend
    [string]$GoldenDir,

    # Minimum .pnpm directory entries for the source to count as healthy
    # (2026-11-15 measured healthy value: 463).
    [int]$MinPnpmEntries = 100,

    [switch]$DryRun
)

$ErrorActionPreference = "Stop"

function Get-MainRepoRoot {
    # `git worktree list --porcelain`: the FIRST "worktree" line is always the main worktree.
    $lines = @(& git worktree list --porcelain)
    if ($LASTEXITCODE -ne 0) { throw "git worktree list failed (run inside the reasonix repo or a worktree)" }
    foreach ($line in $lines) {
        if ($line -like "worktree *") { return $line.Substring("worktree ".Length) }
    }
    throw "could not parse main repo root from git worktree list"
}

function Get-NodeModulesStats {
    param([Parameter(Mandatory = $true)][string]$Path)
    $stats = @{
        Exists        = (Test-Path -LiteralPath $Path -PathType Container)
        TscCmd        = $false
        PnpmEntries   = 0
        TopDirs       = 0
        HasTypescript = $false
    }
    if (-not $stats.Exists) { return $stats }
    $stats.TscCmd = (Test-Path -LiteralPath (Join-Path $Path ".bin\tsc.cmd") -PathType Leaf)
    $pnpmDir = Join-Path $Path ".pnpm"
    if (Test-Path -LiteralPath $pnpmDir -PathType Container) {
        $stats.PnpmEntries = @(Get-ChildItem -LiteralPath $pnpmDir -Force -Directory).Count
        $stats.HasTypescript = (@(Get-ChildItem -LiteralPath $pnpmDir -Force -Directory -Filter "typescript@*").Count -gt 0)
    }
    $stats.TopDirs = @(Get-ChildItem -LiteralPath $Path -Force).Count
    return $stats
}

function Assert-NodeModulesHealthy {
    param(
        [Parameter(Mandatory = $true)][string]$Path,
        [Parameter(Mandatory = $true)][hashtable]$Stats,
        [Parameter(Mandatory = $true)][int]$MinPnpm
    )
    if (-not $Stats.Exists) { throw "node_modules missing or not a directory: $Path" }
    if (-not $Stats.TscCmd) { throw "node_modules looks gutted (.bin/tsc.cmd missing): $Path" }
    if ($Stats.PnpmEntries -lt $MinPnpm) {
        throw ("node_modules .pnpm too small ({0} < {1}), refusing to treat as healthy source: {2}" -f $Stats.PnpmEntries, $MinPnpm, $Path)
    }
    if (-not $Stats.HasTypescript) { throw "node_modules .pnpm has no typescript@* entry: $Path" }
}

# --- resolve paths -----------------------------------------------------------

$mainRepoRoot = Get-MainRepoRoot
if (-not $SourceDir) { $SourceDir = Join-Path $mainRepoRoot "desktop\frontend\node_modules" }
if (-not $GoldenDir) { $GoldenDir = Join-Path (Split-Path -Parent $mainRepoRoot) "golden\node_modules-desktop-frontend" }

Write-Host "== tl1597 golden backup =="
Write-Host ("source : $SourceDir")
Write-Host ("golden : $GoldenDir")
Write-Host ("dry-run: {0}" -f [bool]$DryRun)

# --- health precheck on the source (never back up a gutted state) -----------

$srcStats = Get-NodeModulesStats -Path $SourceDir
Assert-NodeModulesHealthy -Path $SourceDir -Stats $srcStats -MinPnpm $MinPnpmEntries
Write-Host ("source health: OK (.bin/tsc.cmd present, .pnpm entries={0}, top-level entries={1}, typescript present={2})" -f $srcStats.PnpmEntries, $srcStats.TopDirs, $srcStats.HasTypescript)

# --- dry-run: report the plan and stop --------------------------------------

if ($DryRun) {
    $existing = Test-Path -LiteralPath $GoldenDir
    Write-Host "DRY-RUN plan:"
    Write-Host ("  1. robocopy /MIR `"$SourceDir`" -> `"$GoldenDir`" ({0})" -f $(if ($existing) { "update existing golden (mirror)" } else { "create new golden" }))
    Write-Host ("  2. write manifest.json into golden (timestamp, .pnpm entries={0}, top entries={1})" -f $srcStats.PnpmEntries, $srcStats.TopDirs)
    Write-Host "DRY-RUN: nothing copied. Re-run without -DryRun to execute."
    exit 0
}

# --- mirror copy -------------------------------------------------------------

$sw = [System.Diagnostics.Stopwatch]::StartNew()
New-Item -ItemType Directory -Force -Path $GoldenDir | Out-Null
# robocopy /MIR mirrors the tree (adds/updates/removes). Exit codes 0-7 are
# success-ish (1 = files copied); >= 8 means failure.
$null = & robocopy $SourceDir $GoldenDir /MIR /NFL /NDL /NJH /NJS /NP /R:2 /W:2
$rc = $LASTEXITCODE
$sw.Stop()
if ($rc -ge 8) {
    throw "robocopy failed with exit code $rc after $($sw.Elapsed.TotalSeconds.ToString('0.0'))s (golden may be incomplete; do NOT trust it until a successful rerun)"
}

# --- verify the copy, then write manifest ------------------------------------

$goldenStats = Get-NodeModulesStats -Path $GoldenDir
Assert-NodeModulesHealthy -Path $GoldenDir -Stats $goldenStats -MinPnpm $MinPnpmEntries

$manifest = [ordered]@{
    createdAtLocal = (Get-Date -Format "yyyy-MM-dd HH:mm:ss")
    sourceDir      = $SourceDir
    goldenDir      = $GoldenDir
    mainRepoRoot   = $mainRepoRoot
    pnpmEntries    = $goldenStats.PnpmEntries
    topLevelDirs   = $goldenStats.TopDirs
    robocopyExit   = $rc
    backupSeconds  = [math]::Round($sw.Elapsed.TotalSeconds, 1)
}
$manifest | ConvertTo-Json | Set-Content -LiteralPath (Join-Path $GoldenDir "manifest.json") -Encoding UTF8

$sizeGb = [math]::Round(((Get-ChildItem -LiteralPath $GoldenDir -Recurse -Force -ErrorAction SilentlyContinue | Measure-Object -Property Length -Sum).Sum / 1GB), 2)
Write-Host ("backup DONE in {0}s (robocopy exit {1}): .pnpm entries={2}, top entries={3}, size={4}GB" -f $sw.Elapsed.TotalSeconds.ToString("0.0"), $rc, $goldenStats.PnpmEntries, $goldenStats.TopDirs, $sizeGb)
Write-Host ("manifest: " + (Join-Path $GoldenDir "manifest.json"))
